package com.stasdoto.medieval.history;

/** The building and dress traditions of a region around 1050 (each settlement is built in its own region's way). */
public enum Culture {
	RUS("Русь", "деревянные срубы, рубленые городни и детинцы, первые каменные храмы"),
	BYZANTINE("Византия", "камень и кирпич в полосах, купола, черепица, высокие стены"),
	LATIN("Латинский Запад", "романские каменные храмы, фахверк, соломенные и тесовые крыши, мотт-и-бейли"),
	NORSE("Скандинавия", "длинные дома с дёрном и тёсом, ставкирки, валы и частоколы"),
	WEST_SLAV("Западные славяне", "срубы и фахверк, городища на валах, первые каменные ротонды"),
	MAGYAR("Венгрия", "мазанки и полуземлянки, деревянно-земляные крепости, первые каменные храмы"),
	STEPPE("Степь", "юрты и кибитки, кочевья, зимники"),
	ANDALUSI("Аль-Андалус", "белёные дворы, подковообразные арки, плоские крыши, медины"),
	ARAB("Арабский Восток", "сырцовый кирпич, плоские крыши, внутренние дворы, минареты"),
	PERSIAN("Иран и Туран", "кирпич и изразцы, купола, караван-сараи, высокие стены"),
	CAUCASUS("Кавказ", "камень, башни, храмы с коническими куполами"),
	BALT_FINN("Балты и финны", "срубы, городища на холмах, священные рощи"),
	CELTIC("Ирландия и Шотландия", "круглые дома, каменные башни монастырей, кранноги");

	public final String title;
	public final String look;

	Culture(String title, String look) {
		this.title = title;
		this.look = look;
	}
}
